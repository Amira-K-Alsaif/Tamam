"""Store original knowledge documents in Supabase Storage."""

import re
from pathlib import PurePosixPath

from supabase import Client

from app.modules.knowledge.schemas import Document
from app.modules.knowledge.upload_validation import validate_upload

BUCKET_NAME = "knowledge-documents"

CONTENT_TYPES = {
    ".pdf": "application/pdf",
    ".docx": ("application/vnd.openxmlformats-officedocument.wordprocessingml.document"),
    ".md": "text/markdown",
    ".txt": "text/plain",
}


def upload_original_document(
    db: Client,
    document: Document,
    content: bytes,
) -> str:
    """Upload an original document to the private bucket."""

    # Only accept paths generated by our ingestion service.
    if not re.fullmatch(r"upload-[0-9a-f]{32}", document.id):
        raise ValueError("Invalid uploaded document ID")

    path = document.file_path
    prefix = f"uploads/{document.id}/"

    if not path.startswith(prefix):
        raise ValueError("Invalid storage path")

    filename = path.removeprefix(prefix)
    validate_upload(filename, content)

    if "/" in filename or "\\" in filename:
        raise ValueError("Invalid filename")

    extension = PurePosixPath(filename).suffix.lower()

    db.storage.from_(BUCKET_NAME).upload(
        path=path,
        file=content,
        file_options={
            "content-type": CONTENT_TYPES[extension],
            "upsert": "false",
        },
    )

    return path
