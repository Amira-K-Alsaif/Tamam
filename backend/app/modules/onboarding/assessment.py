"""The starting assessment: what a new hire already knows, measured from the policies.

A few questions per topic, generated by the model from each topic's policy document and
checked against its text like the lesson quizzes. The scores replace guesswork: a topic
scored below the passing score becomes a lesson on the roadmap. The answer key never leaves
the server.
"""

from concurrent.futures import ThreadPoolExecutor

from . import mock_data, quiz, service
from .schemas import Assessment, AssessmentOutcome, AssessmentQuestion, TopicScore

QUESTIONS_PER_TOPIC = 2

# One assessment per server run: the questions, the right option for each, and its topic.
_assessment: tuple[Assessment, list[int], list[str]] | None = None


def _generate(topic: str, document_id: str):
    try:
        questions, key = quiz.generate_questions(document_id, QUESTIONS_PER_TOPIC)
    except quiz.QuizUnavailableError:
        return topic, [], []
    # The model may write more than asked; the assessment stays short.
    return topic, questions[:QUESTIONS_PER_TOPIC], key[:QUESTIONS_PER_TOPIC]


def get_assessment() -> Assessment:
    """Generates every topic's questions at once, so the wait is one model call, not five."""
    global _assessment
    if _assessment is None:
        topics = mock_data.TOPIC_DOCUMENTS.items()
        with ThreadPoolExecutor(max_workers=len(topics)) as pool:
            generated = list(pool.map(lambda pair: _generate(*pair), topics))

        questions: list[AssessmentQuestion] = []
        key: list[int] = []
        topic_of: list[str] = []
        # A topic whose questions could not be traced to its document is left out, not guessed.
        for topic, topic_questions, topic_key in generated:
            questions += [
                AssessmentQuestion(**q.model_dump(), topic=topic) for q in topic_questions
            ]
            key += topic_key
            topic_of += [topic] * len(topic_questions)
        if not questions:
            raise quiz.QuizUnavailableError("No topic produced a usable question")
        _assessment = (Assessment(questions=questions), key, topic_of)
    return _assessment[0]


def grade_assessment(employee_id: str, answers: list[int]) -> AssessmentOutcome:
    """Scores each topic, records the scores, and says which options were right."""
    if _assessment is None:
        raise LookupError("Open the assessment before answering it")
    _, key, topic_of = _assessment
    if len(answers) != len(key):
        raise ValueError("One answer per question is required")

    correct = [given == right for given, right in zip(answers, key, strict=True)]
    right_per_topic: dict[str, list[bool]] = {}
    for topic, is_right in zip(topic_of, correct, strict=True):
        right_per_topic.setdefault(topic, []).append(is_right)
    scores = {
        topic: round(sum(marks) * 100 / len(marks)) for topic, marks in right_per_topic.items()
    }

    service.record_scores(employee_id, scores)
    return AssessmentOutcome(
        scores=[
            TopicScore(topic=topic, score=score, passed=score >= service.PASSING_SCORE)
            for topic, score in scores.items()
        ],
        correct=correct,
        correct_options=key,
    )


def clear_assessment() -> None:
    """Forgets the generated assessment; for tests."""
    global _assessment
    _assessment = None
